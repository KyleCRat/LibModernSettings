#Requires -Version 7.4
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot '../tools/Update-IconNames.ps1')

function Assert-IconTest {
    param([bool]$Result, [string]$Message)
    if (-not $Result) {
        throw $Message
    }
}

function Assert-IconFailure {
    param([scriptblock]$Action)
    $failed = $false
    try {
        & $Action | Out-Null
    } catch {
        $failed = $true
    }
    Assert-IconTest $failed 'Expected invalid input to fail.'
}

$utf8 = [Text.UTF8Encoding]::new($false)
$sample = @(
    '30;Interface/Icons/Sub/INV_Fire.blp'
    '10;interface\icons\Ability_Test.BLP'
    '30;interface/icons/sub/inv_fire.blp'
    '20;Interface/Other/Ignored.blp'
    '40;Sound/Ignored.ogg'
) -join "`n"
$bytes = $utf8.GetBytes($sample + "`n")
$icons = ConvertTo-IconNames -Bytes $bytes
Assert-IconTest ($icons.Count -eq 2) 'Only icon textures should be extracted.'
Assert-IconTest ($icons[10] -ceq 'Ability_Test') 'Preserve useful filename spelling.'
Assert-IconTest ($icons[30] -ceq 'Sub\INV_Fire') 'Normalize separators and duplicate casing deterministically.'
$reversed = ConvertTo-IconNames -Bytes $utf8.GetBytes(($sample.Split("`n")[4..0] -join "`n") + "`n")
$manifest = [ordered]@{
    schema = 1
    repository = 'https://github.com/wowdev/wow-listfile'
    release = '202610200222'
    publishedAt = '2026-10-20T02:23:11Z'
    commit = '041822f2ed2efcc866eb728296e190038897539f'
    path = 'parts/interface.csv'
    gitBlob = Get-IconNameDigest -Bytes $bytes -GitBlob
    sourceBytes = $bytes.Length
    sha256 = Get-IconNameDigest -Bytes $bytes
}
$lua = ConvertTo-IconNameLua -Icons $icons -Manifest $manifest -Minor 11
Assert-IconTest ($lua -ceq (ConvertTo-IconNameLua -Icons $reversed -Manifest $manifest -Minor 11)) 'Input ordering must not change generated bytes.'
Assert-IconTest (-not $lua.Contains("`r")) 'Generated Lua must use LF.'
Assert-IconTest ($lua.EndsWith("`n", [StringComparison]::Ordinal)) 'Generated Lua requires a final newline.'
Assert-IconTest ($lua.Contains('local MAJOR, MINOR = "LibModernSettings-1.0", 11')) 'Use the implementation guard without incrementing it.'

Assert-IconFailure { ConvertTo-IconNames -Bytes $utf8.GetBytes('not a listfile') }
Assert-IconFailure { ConvertTo-IconNames -Bytes $utf8.GetBytes('10;Interface/Other/NotAnIcon.blp') }
Assert-IconFailure { ConvertTo-IconNames -Bytes $utf8.GetBytes("10;Interface/Icons/One.blp`n10;Interface/Icons/Two.blp") }
Assert-IconFailure { ConvertTo-IconNames -Bytes $utf8.GetBytes('10;Interface/Icons/a]=]b.blp') }
Assert-IconFailure { ConvertTo-IconNames -Bytes ([byte[]]@(255, 255)) }

$many = [Collections.Generic.SortedDictionary[int, string]]::new()
foreach ($id in 1..257) {
    $many.Add($id, "Icon_$id")
}
$chunked = ConvertTo-IconNameLua -Icons $many -Manifest $manifest -Minor 11
Assert-IconTest ($chunked.Contains('{ 1, 128, [=[') -and $chunked.Contains('{ 129, 256, [=[') -and
    $chunked.Contains('{ 257, 257, [=[')) 'Generated blocks must bound decoding to 128 names.'

$temporary = [IO.Path]::GetTempFileName()
try {
    [IO.File]::WriteAllBytes($temporary, $bytes)
    $verified = Get-IconNameSourceBytes -Manifest $manifest -LocalFile $temporary
    Assert-IconTest ((Get-IconNameDigest -Bytes $verified) -eq $manifest.sha256) 'Pinned local input should verify.'
    [IO.File]::WriteAllText($temporary, 'changed')
    Assert-IconFailure { Get-IconNameSourceBytes -Manifest $manifest -LocalFile $temporary }
    Assert-IconFailure { Write-IconNameOutput -Path $temporary -Content $lua -VerifyOnly }
    Assert-IconTest ([IO.File]::ReadAllText($temporary) -eq 'changed') 'Check mode must not write.'
    Write-IconNameOutput -Path $temporary -Content $lua
    Write-IconNameOutput -Path $temporary -Content $lua -VerifyOnly
    $written = [IO.File]::ReadAllBytes($temporary)
    Assert-IconTest (-not ($written[0] -eq 239 -and $written[1] -eq 187 -and $written[2] -eq 191)) 'Do not write a UTF-8 BOM.'
} finally {
    Remove-Item -LiteralPath $temporary
}

# Mock metadata only; these tests never contact GitHub.
$script:testPublished = [DateTimeOffset]::UtcNow
function Invoke-RestMethod {
    param($Uri, $Headers)
    if ($Uri.EndsWith('/releases/latest')) {
        return @{
            tag_name = '202610200222'
            published_at = $script:testPublished
            draft = $false
            prerelease = $false
        }
    }
    if ($Uri.Contains('/git/ref/tags/')) {
        return @{ object = @{ type = 'commit'; sha = '041822f2ed2efcc866eb728296e190038897539f' } }
    }
    return @{ type = 'file'; sha = 'dfda2c603fd66b0d807205308b1d2b02086bf2fb'; size = 1234 }
}
$latest = Get-LatestIconNameSource -MaximumAge 72
Assert-IconTest ($latest.release -eq '202610200222' -and $latest.sourceBytes -eq 1234) 'Resolve the latest published source.'
$script:testPublished = [DateTimeOffset]::UtcNow.AddDays(-4)
Assert-IconFailure { Get-LatestIconNameSource -MaximumAge 72 }
Write-Host 'LibModernSettings icon-name extraction tests passed'
