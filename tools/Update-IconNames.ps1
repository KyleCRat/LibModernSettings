#Requires -Version 7.4
<#
.SYNOPSIS
Build the picker's compact icon-name index from wowdev/wow-listfile.
.DESCRIPTION
By default, resolve the latest published release and pin its interface list.
Use -Pinned to regenerate the recorded snapshot, or -Check to verify it without
writing. -SourceFile allows either pinned operation to run without a download.
No downloaded code is executed. Only Interface/Icons/*.blp filename mappings
are retained; the generated index does not enumerate icons in the game.
#>
[CmdletBinding()]
param(
    [switch]$Pinned,
    [switch]$Check,
    [string]$SourceFile,
    [ValidateRange(1, 8760)]
    [int]$MaxAgeHours = 72
)

$ErrorActionPreference = 'Stop'
$IconNameRepository = 'wowdev/wow-listfile'
$IconNameHeaders = @{
    'User-Agent' = 'LibModernSettings-icon-names'
    'Accept' = 'application/vnd.github+json'
    'Cache-Control' = 'no-cache'
}

function Get-IconNameDigest {
    param([byte[]]$Bytes, [switch]$GitBlob)

    $algorithm = if ($GitBlob) { 'SHA1' } else { 'SHA256' }
    $hash = [Security.Cryptography.IncrementalHash]::CreateHash($algorithm)
    try {
        if ($GitBlob) {
            $prefix = [Text.Encoding]::ASCII.GetBytes("blob $($Bytes.Length)" + [char]0)
            $hash.AppendData($prefix)
        }
        $hash.AppendData($Bytes)
        return [Convert]::ToHexString($hash.GetHashAndReset()).ToLowerInvariant()
    } finally {
        $hash.Dispose()
    }
}

function ConvertTo-IconNames {
    param([byte[]]$Bytes)

    $encoding = [Text.UTF8Encoding]::new($false, $true)
    $text = $encoding.GetString($Bytes).TrimStart([char]0xFEFF)
    $icons = [Collections.Generic.SortedDictionary[int, string]]::new()
    $lineNumber = 0
    foreach ($line in $text.Split("`n")) {
        $lineNumber++
        $line = $line.TrimEnd("`r")
        if ($line.Length -eq 0) {
            continue
        }
        if ($line -notmatch '^(?<id>[1-9][0-9]*);(?<path>[^;\x00-\x1f]+)$') {
            throw "Invalid listfile row $lineNumber; expected FileDataID;filename."
        }
        $fileID = [int]::Parse($Matches.id, [Globalization.CultureInfo]::InvariantCulture)
        $path = $Matches.path.Replace('\', '/')
        if ($path -notmatch '(?i)^interface/icons/(?<name>.+)\.blp$') {
            continue
        }
        $name = $Matches.name.Replace('/', '\')
        if ($name.Contains(']=]')) {
            throw "Unsupported Lua delimiter in icon filename on row $lineNumber."
        }
        if ($icons.ContainsKey($fileID)) {
            if (-not [string]::Equals($icons[$fileID], $name, [StringComparison]::OrdinalIgnoreCase)) {
                throw "Conflicting filenames for icon $fileID."
            }
            if ([string]::CompareOrdinal($name, $icons[$fileID]) -lt 0) {
                $icons[$fileID] = $name
            }
        } else {
            $icons.Add($fileID, $name)
        }
    }
    if ($icons.Count -eq 0) {
        throw 'The source contains no Interface/Icons/*.blp names.'
    }
    return ,$icons
}

function ConvertTo-IconNameLua {
    param(
        [Collections.Generic.SortedDictionary[int, string]]$Icons,
        $Manifest,
        [int]$Minor
    )

    $output = [Text.StringBuilder]::new()
    [void]$output.Append(@"
-- Generated by tools/Update-IconNames.ps1; do not edit by hand.
-- Source: https://github.com/$IconNameRepository
-- Release: $($Manifest.release) ($($Manifest.publishedAt))
-- Commit: $($Manifest.commit)
-- Source SHA-256: $($Manifest.sha256)
-- Community filenames are search metadata, not verified gameplay relationships.
local MAJOR, MINOR = "LibModernSettings-1.0", $Minor
local lib = LibStub(MAJOR, true)
if not lib or lib._implementationMinor ~= MINOR
    or not lib:_BeginModule("IconPicker/NameData", MINOR) then
    return
end

lib._iconNameIndex = {
    revision = "$($Manifest.release)",
    count = $($Icons.Count),
    -- Each block contains at most 128 names; decode only blocks being searched.
    blocks = {

"@)
    $entries = @($Icons.GetEnumerator())
    for ($start = 0; $start -lt $entries.Count; $start += 128) {
        $end = [Math]::Min($start + 127, $entries.Count - 1)
        [void]$output.Append("        { $($entries[$start].Key), $($entries[$end].Key), [=[`n")
        for ($index = $start; $index -le $end; $index++) {
            [void]$output.Append("$($entries[$index].Key);$($entries[$index].Value)`n")
        }
        [void]$output.Append("]=] },`n")
    }
    [void]$output.Append("    },`n}`n")
    return $output.ToString().Replace("`r`n", "`n")
}

function Get-LatestIconNameSource {
    param([int]$MaximumAge)

    $base = "https://api.github.com/repos/$IconNameRepository"
    $release = Invoke-RestMethod -Uri "$base/releases/latest" -Headers $IconNameHeaders
    if ($release.draft -or $release.prerelease -or $release.tag_name -notmatch '^[0-9]{12}$') {
        throw 'GitHub did not return a published listfile release with the expected tag format.'
    }
    $published = [DateTimeOffset]$release.published_at
    $age = ([DateTimeOffset]::UtcNow - $published).TotalHours
    if ($age -gt $MaximumAge -or $age -lt -1) {
        throw "The latest listfile release is $([Math]::Round($age, 1)) hours old. Inspect upstream before deliberately increasing -MaxAgeHours."
    }
    $reference = Invoke-RestMethod -Uri "$base/git/ref/tags/$($release.tag_name)" -Headers $IconNameHeaders
    $object = $reference.object
    if ($object.type -eq 'tag') {
        $annotated = Invoke-RestMethod -Uri "$base/git/tags/$($object.sha)" -Headers $IconNameHeaders
        $object = $annotated.object
    }
    if ($object.type -ne 'commit' -or $object.sha -notmatch '^[0-9a-f]{40}$') {
        throw 'The published listfile tag did not resolve to a commit.'
    }
    $commit = $object.sha
    $file = Invoke-RestMethod -Uri "$base/contents/parts/interface.csv?ref=$commit" -Headers $IconNameHeaders
    if ($file.type -ne 'file' -or $file.sha -notmatch '^[0-9a-f]{40}$' -or $file.size -le 0) {
        throw 'Invalid interface-list metadata from GitHub.'
    }
    return [ordered]@{
        schema = 1
        repository = "https://github.com/$IconNameRepository"
        release = $release.tag_name
        publishedAt = $published.ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ')
        commit = $commit
        path = 'parts/interface.csv'
        gitBlob = $file.sha
        sourceBytes = $file.size
    }
}

function Get-IconNameSourceBytes {
    param($Manifest, [string]$LocalFile)

    if ($Manifest.schema -ne 1 -or $Manifest.repository -ne "https://github.com/$IconNameRepository" -or
        $Manifest.commit -notmatch '^[0-9a-f]{40}$' -or
        $Manifest.path -ne 'parts/interface.csv' -or
        $Manifest.gitBlob -notmatch '^[0-9a-f]{40}$' -or
        $Manifest.release -notmatch '^[0-9]{12}$') {
        throw 'Invalid icon-name source manifest.'
    }
    if ($LocalFile) {
        $bytes = [IO.File]::ReadAllBytes((Resolve-Path -LiteralPath $LocalFile).Path)
    } else {
        $uri = "https://raw.githubusercontent.com/$IconNameRepository/$($Manifest.commit)/$($Manifest.path)"
        $temporary = [IO.Path]::GetTempFileName()
        try {
            Write-Host "Downloading $uri to a temporary file."
            Invoke-WebRequest -Uri $uri -Headers $IconNameHeaders -OutFile $temporary
            $bytes = [IO.File]::ReadAllBytes($temporary)
        } finally {
            Remove-Item -LiteralPath $temporary
        }
    }
    if ($bytes.Length -ne $Manifest.sourceBytes -or
        (Get-IconNameDigest -Bytes $bytes -GitBlob) -ne $Manifest.gitBlob) {
        throw 'The downloaded size or Git blob hash differs from the pinned GitHub file.'
    }
    if ($Manifest.sha256 -and (Get-IconNameDigest -Bytes $bytes) -ne $Manifest.sha256) {
        throw 'The source SHA-256 differs from the recorded snapshot.'
    }
    return ,$bytes
}

function Write-IconNameOutput {
    param([string]$Path, [string]$Content, [switch]$VerifyOnly)

    $bytes = [Text.UTF8Encoding]::new($false).GetBytes($Content)
    if (Test-Path -LiteralPath $Path) {
        $existing = [IO.File]::ReadAllBytes($Path)
        if ((Get-IconNameDigest -Bytes $existing) -eq (Get-IconNameDigest -Bytes $bytes)) {
            return
        }
    }
    if ($VerifyOnly) {
        throw "Generated file differs: $Path"
    }
    [IO.File]::WriteAllBytes($Path, $bytes)
}

function Invoke-IconNameUpdate {
    param(
        [switch]$Pinned,
        [switch]$Check,
        [string]$SourceFile,
        [int]$MaxAgeHours
    )

    $root = Split-Path -Parent $PSScriptRoot
    $manifestPath = Join-Path $root 'IconPicker/NameData.source.json'
    $outputPath = Join-Path $root 'IconPicker/NameData.lua'
    if ($SourceFile -and -not ($Pinned -or $Check)) {
        throw '-SourceFile requires -Pinned or -Check so the input can be verified against the recorded snapshot.'
    }
    $manifest = if ($Pinned -or $Check) {
        Get-Content -LiteralPath $manifestPath -Raw | ConvertFrom-Json -AsHashtable
    } else {
        Get-LatestIconNameSource -MaximumAge $MaxAgeHours
    }
    $bytes = Get-IconNameSourceBytes -Manifest $manifest -LocalFile $SourceFile
    $icons = ConvertTo-IconNames -Bytes $bytes
    # Canonical field order and UTC text avoid JSON/date/culture round-trip drift.
    $manifest = [ordered]@{
        schema = 1
        repository = $manifest.repository
        release = $manifest.release
        publishedAt = ([DateTimeOffset]$manifest.publishedAt).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ')
        commit = $manifest.commit
        path = $manifest.path
        gitBlob = $manifest.gitBlob
        sourceBytes = $bytes.Length
        sha256 = Get-IconNameDigest -Bytes $bytes
        iconCount = $icons.Count
        filter = 'Interface/Icons/*.blp; FileDataID -> basename without extension'
    }
    $core = Get-Content -LiteralPath (Join-Path $root 'LibModernSettings-1.0.lua') -Raw
    if ($core -notmatch 'local MAJOR, MINOR = "LibModernSettings-1.0", ([0-9]+)') {
        throw 'Cannot determine the current library implementation MINOR.'
    }
    $generated = ConvertTo-IconNameLua -Icons $icons -Manifest $manifest -Minor ([int]$Matches[1])
    $manifestText = ($manifest | ConvertTo-Json -Depth 4).Replace("`r`n", "`n") + "`n"
    Write-IconNameOutput -Path $outputPath -Content $generated -VerifyOnly:$Check
    Write-IconNameOutput -Path $manifestPath -Content $manifestText -VerifyOnly:$Check
    $verb = if ($Check) { 'Verified' } else { 'Generated' }
    Write-Host "$verb $($icons.Count) icon names from release $($manifest.release): $([Text.Encoding]::UTF8.GetByteCount($generated)) bytes."
}

# Dot-sourcing exposes the pure extraction helpers to library tests without I/O.
if ($MyInvocation.InvocationName -ne '.') {
    Invoke-IconNameUpdate -Pinned:$Pinned -Check:$Check -SourceFile $SourceFile -MaxAgeHours $MaxAgeHours
}
